/**
 * Site.social_links keys the admin is likely to type, mapped to the icon that
 * should represent them. Anything not listed and not itself an icon name gets
 * the globe.
 */
const ALIASES: Record<string, string> = {
  email: 'envelope',
  mail: 'envelope',
  'e-mail': 'envelope',
  twitter: 'x',
  'twitter-x': 'x',
  fb: 'facebook',
  ig: 'instagram',
  insta: 'instagram',
  yt: 'youtube',
  'linked-in': 'linkedin',
  website: 'globe',
  web: 'globe',
};

export function socialIconPath(key: string): string {
  const name = key.trim().toLowerCase();
  return SOCIAL_ICON_PATHS[ALIASES[name] ?? name] ?? SOCIAL_ICON_PATHS['globe'];
}

/**
 * The order icons appear in, most-used first.
 *
 * Not the admin's insertion order, because there is none to honour: Site
 * .social_links is a Django JSONField, which is jsonb on Postgres, and jsonb
 * stores an object's keys in its own order rather than the one they were typed
 * in — `{email, instagram, facebook}` comes back alphabetised. Sorting here is
 * what makes the row deterministic instead of surprising.
 *
 * Keys not listed follow, alphabetically.
 */
// Canonical icon names, not the admin's keys: socialSortKey resolves aliases
// before looking a key up here, so "email" arrives as "envelope".
const DISPLAY_ORDER = [
  'envelope',
  'instagram',
  'facebook',
  'x',
  'whatsapp',
  'threads',
  'tiktok',
  'youtube',
  'linkedin',
  'substack',
  'mastodon',
  'globe',
];

/** Sort key for a social_links entry: listed networks first, then A-Z. */
export function socialSortKey(key: string): [number, string] {
  const name = key.trim().toLowerCase();
  const canonical = ALIASES[name] ?? name;
  const rank = DISPLAY_ORDER.indexOf(canonical);
  return [rank === -1 ? DISPLAY_ORDER.length : rank, canonical];
}
